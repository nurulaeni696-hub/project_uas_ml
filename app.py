def get_kecamatan_coords(kab, kec):
    """Ambil koordinat kecamatan. Fallback ke koordinat kabupaten jika tidak ada."""
    key = (kab.strip().upper(), kec.strip().upper())
    if key in KECAMATAN_COORDS:
        return KECAMATAN_COORDS[key]
    # Coba partial match pada nama kecamatan
    kab_upper = kab.strip().upper()
    kec_upper = kec.strip().upper()
    for (k, c), coords in KECAMATAN_COORDS.items():
        if k == kab_upper and (kec_upper in c or c in kec_upper):
            return coords
    # Fallback ke pusat kabupaten
    return KABUPATEN_FALLBACK.get(kab_upper, (-6.9175, 107.6191))


